// The three policy controllers declare the objects they generate as server-side apply
// configurations (api/v1alpha1/applyconfiguration, generated by `make generate`) and send
// them with client.Apply, so the policy's field manager owns exactly the fields it sets.
// A field that disappears from the desired object on a later pass is therefore removed
// from the live object instead of lingering, which a read-modify-write patch of the typed
// struct could not guarantee.

// specApplyConfiguration converts a typed spec into the generated apply configuration of
// the same type (AC is the apply configuration struct, for example
// RecordSpecApplyConfiguration) by way of JSON.
//
// The detour keeps the planners' typed specs as the single source of truth, so a new
// spec field flows into the applied object without a hand-written mapping. It is also
// checked: when the generated package is older than the API types and would silently
// drop a field, the conversion fails with a pointer to `make generate` instead.
func specApplyConfiguration[AC any](spec any) (*AC, error) {
	raw, err := json.Marshal(spec)
	if err != nil {
		return nil, fmt.Errorf("encoding %T: %w", spec, err)
	}
	if raw, err = omitEmptyObjects(raw); err != nil {
		return nil, fmt.Errorf("encoding %T: %w", spec, err)
	}
	out := new(AC)
	if err := json.Unmarshal(raw, out); err != nil {
		return nil, fmt.Errorf("decoding %T into %T: %w", spec, out, err)
	}
	back, err := json.Marshal(out)
	if err != nil {
		return nil, fmt.Errorf("encoding %T: %w", out, err)
	}
	same, err := sameJSON(raw, back)
	if err != nil {
		return nil, err
	}
	if !same {
		return nil, fmt.Errorf("%T does not carry every field of %T; the generated apply configurations are stale, run make generate",
			out, spec)
	}
	return out, nil
}

// omitEmptyObjects drops top-level spec fields whose value is an empty JSON object, such as
// connectionRef: {} or lifecycle: {} when the policy sets nothing inside them. Kubernetes
// 1.29, the OpenShift 4.16 floor, rejects an apply that empties an optional object this
// field manager previously filled: the merge turns the object into null and validation
// fails with a 422. Leaving the field out instead makes server-side apply remove what this
// manager set before, which is the intended result on every version. Only the top level is
// pruned; nested empty objects, such as a Record rdata block, keep their meaning.
func omitEmptyObjects(raw []byte) ([]byte, error) {
	var fields map[string]any
	if err := json.Unmarshal(raw, &fields); err != nil {
		return nil, err
	}
	for k, v := range fields {
		if obj, ok := dropNulls(v).(map[string]any); ok && len(obj) == 0 {
			delete(fields, k)
		}
	}
	return json.Marshal(fields)
}

// sameJSON reports whether two JSON documents hold the same data, ignoring key order and
// null values: an omitted field and an explicit null mean the same to server-side apply.
func sameJSON(a, b []byte) (bool, error) {
	var av, bv any
	if err := json.Unmarshal(a, &av); err != nil {
		return false, err
	}
	if err := json.Unmarshal(b, &bv); err != nil {
		return false, err
	}
	return reflect.DeepEqual(dropNulls(av), dropNulls(bv)), nil
}

// dropNulls removes null-valued keys from decoded JSON objects, recursively.
func dropNulls(v any) any {
	switch t := v.(type) {
	case map[string]any:
		out := make(map[string]any, len(t))
		for k, val := range t {
			if val == nil {
				continue
			}
			out[k] = dropNulls(val)
		}
		return out
	case []any:
		out := make([]any, len(t))
		for i, val := range t {
			out[i] = dropNulls(val)
		}
		return out
	default:
		return v
	}
}

// controllerOwnerReference builds the controller ownerReference an object generated for
// owner carries, taking the owner's group, version and kind from the scheme. It is what
// controllerutil.SetControllerReference sets on a typed object.
func controllerOwnerReference(owner client.Object, scheme *runtime.Scheme) (*metav1ac.OwnerReferenceApplyConfiguration, error) {
	gvk, err := apiutil.GVKForObject(owner, scheme)
	if err != nil {
		return nil, err
	}
	return controllerReference(gvk.GroupVersion().String(), gvk.Kind, owner.GetName(), owner.GetUID()), nil
}

// controllerReference is a controller ownerReference with blockOwnerDeletion, the shape
// Kubernetes garbage collection expects of a generated object's single owner.
func controllerReference(apiVersion, kind, name string, uid types.UID) *metav1ac.OwnerReferenceApplyConfiguration {
	return metav1ac.OwnerReference().
		WithAPIVersion(apiVersion).
		WithKind(kind).
		WithName(name).
		WithUID(uid).
		WithController(true).
		WithBlockOwnerDeletion(true)
}
