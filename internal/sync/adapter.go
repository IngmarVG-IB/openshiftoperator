// Package sync holds the one generic object-layer reconcile loop every object kind
// runs, parameterised by a small per-kind Adapter. See DESIGN.md section 5.
package sync

import (
	"context"
	"errors"
	"fmt"

	apierrors "k8s.io/apimachinery/pkg/api/errors"
	"k8s.io/apimachinery/pkg/types"
	"sigs.k8s.io/controller-runtime/pkg/client"

	uddiv1alpha1 "github.com/IngmarVG-IB/openshiftoperator/api/v1alpha1"
	"github.com/IngmarVG-IB/openshiftoperator/internal/uddi"
)

// ErrDependencyNotReady is returned by Adapter.Resolve when a referenced object has no
// Universal DDI id yet. The loop turns it into Ready=False/DependencyNotReady and
// requeues instead of failing.
var ErrDependencyNotReady = errors.New("sync: dependency not ready")

// ErrConflict is returned by Adapter.Find when a matching Universal DDI object exists
// but must never be adopted, updated or deleted, regardless of lifecycle.adoptExisting.
// Record uses this for a match whose source is not STATIC (DESIGN.md section 4.3): the
// normal found-but-unowned path honours adoptExisting, but a non-STATIC record is never
// eligible for adoption at all. Wrap ErrConflict with a message naming why (for example
// the object's source); the loop reports Ready=False/AlreadyExists with that message
// instead of attempting to create, adopt, patch or delete anything.
var ErrConflict = errors.New("sync: object exists and cannot be adopted")

// Deps maps an adapter-chosen key ("view", "zone", "space", "parent", ...) to the
// resolved Universal DDI resource id.
type Deps map[string]string

// Object is the contract every object-layer CR satisfies. S is the kind's spec type.
// The accessors are generated by hand in api/v1alpha1/accessors.go; each kind's spec
// inlines CommonSpec and each kind's status inlines ObjectStatus, so they are
// one-liners.
type Object[S any] interface {
	client.Object

	// SpecOf returns a pointer to the kind's spec.
	SpecOf() *S
	// StatusOf returns a pointer to the ObjectStatus inlined in the kind's status.
	StatusOf() *uddiv1alpha1.ObjectStatus
	// ConnectionName returns spec.connectionRef.name, defaulted to "default".
	ConnectionName() string
	// LifecycleOf returns spec.lifecycle.
	LifecycleOf() uddiv1alpha1.Lifecycle
	// SpecTags returns spec.tags.
	SpecTags() map[string]string
}

// Adapter maps one CR kind onto its Universal DDI counterpart. S is the CR's spec type,
// U the SDK model type (for example dnsconfig.View).
//
// Everything is stateless per call: the loop owns the ordering, the conditions, the
// finalizer and the ownership tags, and the adapter owns the field mapping.
type Adapter[S any, U any] interface {
	// Kind is the CR kind name, used in events, messages and ownership tags.
	Kind() string

	// Resolve turns the spec's ObjectRefs into Universal DDI ids. It returns an error
	// wrapping ErrDependencyNotReady when a referenced object has no id yet.
	Resolve(ctx context.Context, c client.Client, obj client.Object, spec *S) (Deps, error)

	// Find looks the object up by its natural key, for adoption. It returns
	// (nil, nil) when nothing matches.
	Find(ctx context.Context, uc *uddi.Client, spec *S, deps Deps) (*U, error)

	// FindByUID looks the object up by the uddi_operator_uid ownership tag. It recovers
	// from a status write that failed after a successful create, which matters most for
	// next-available allocation where the natural key is not known in advance. It
	// returns (nil, nil) when nothing matches.
	FindByUID(ctx context.Context, uc *uddi.Client, uid string) (*U, error)

	// Create makes the Universal DDI object, with tags already merged by the loop.
	Create(ctx context.Context, uc *uddi.Client, spec *S, deps Deps, tags map[string]string) (*U, error)

	// Get reads the Universal DDI object by id. A 404 is reported as an APIError with
	// IsNotFound() true and makes the loop recreate the object.
	Get(ctx context.Context, uc *uddi.Client, id string) (*U, error)

	// Diff compares the managed fields only and returns a partial patch. Anything the
	// CR does not manage is left alone in Universal DDI.
	Diff(spec *S, deps Deps, tags map[string]string, current *U) (patch *U, changed bool)

	// Update applies a partial patch.
	Update(ctx context.Context, uc *uddi.Client, id string, patch *U) (*U, error)

	// Delete removes the Universal DDI object.
	Delete(ctx context.Context, uc *uddi.Client, id string) error

	// Observe copies observed fields from the Universal DDI object into the CR's
	// kind-specific status. The loop writes id, observedGeneration, lastSyncTime and
	// the conditions itself. Implementations must do nothing rather than panic when
	// current is nil or obj is not the kind they expect.
	Observe(obj client.Object, current *U)

	// IDOf returns the Universal DDI resource id of an object.
	IDOf(current *U) string

	// TagsOf returns the tags currently set on a Universal DDI object.
	TagsOf(current *U) map[string]string
}

// StatusObject is any object-layer CR, used when resolving references generically.
type StatusObject interface {
	client.Object
	// StatusOf returns a pointer to the ObjectStatus inlined in the kind's status.
	StatusOf() *uddiv1alpha1.ObjectStatus
}

// ResolveRef turns an ObjectRef into a Universal DDI resource id.
//
// A ref carrying an id is used as is. A ref carrying a name fetches that CR from the
// same namespace and reads status.id; a missing CR or an empty status.id yields an
// error wrapping ErrDependencyNotReady. into must be an empty CR of the referenced
// kind and is filled in on success, so callers can read more than the id if they need
// to.
func ResolveRef(ctx context.Context, c client.Client, namespace string, ref uddiv1alpha1.ObjectRef, into StatusObject, kind string) (string, error) {
	if ref.ID != "" {
		return ref.ID, nil
	}
	if ref.Name == "" {
		return "", fmt.Errorf("%w: empty %s reference", ErrDependencyNotReady, kind)
	}
	if err := c.Get(ctx, types.NamespacedName{Namespace: namespace, Name: ref.Name}, into); err != nil {
		if apierrors.IsNotFound(err) {
			return "", fmt.Errorf("%w: %s %s/%s does not exist", ErrDependencyNotReady, kind, namespace, ref.Name)
		}
		return "", err
	}
	id := into.StatusOf().ID
	if id == "" {
		return "", fmt.Errorf("%w: %s %s/%s has no status.id yet", ErrDependencyNotReady, kind, namespace, ref.Name)
	}
	return id, nil
}
